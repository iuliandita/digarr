import { readFileSync } from 'node:fs'
import { PGlite } from '@electric-sql/pglite'
import { eq, sql } from 'drizzle-orm'
import { drizzle } from 'drizzle-orm/pglite'
import { migrate } from 'drizzle-orm/pglite/migrator'
import { beforeAll, describe, expect, it } from 'vitest'
import { createBackup, restoreBackup } from '@/core/ops/backup'
import { getPendingMigrations } from '@/core/ops/upgrade'
import { targetAction } from '@/core/targets/lidarr-retry'
import { applyPgliteStatementTimeout } from '@/db/backend'
import {
  getRecommendation,
  listPendingAlbumRecommendations,
  listWaitingApprovals,
  markRecommendationUnaddable,
  updateRecommendationStatus,
} from '@/db/queries/recommendations'
import * as schema from '@/db/schema'

type DB = ReturnType<typeof drizzle<typeof schema>>
let db: DB

beforeAll(async () => {
  const client = new PGlite() // in-memory
  db = drizzle(client, { schema })
  await migrate(db, { migrationsFolder: './drizzle' })
})

describe('pglite backend contract', () => {
  it('applies all repo migrations and creates core tables', async () => {
    const migration = readFileSync('drizzle/0053_shallow_mysterio.sql', 'utf8')
    for (const statement of migration.split('--> statement-breakpoint')) {
      await db.execute(sql.raw(statement))
    }
    const res = await db.execute(
      sql`SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_name IN ('users','settings','artists','playlist_exports')`,
    )
    expect(res.rows.length).toBe(4)
  })

  it('creates nullable text unreconciled reason columns', async () => {
    const res = await db.execute(sql`
      SELECT table_name, column_name, data_type, is_nullable
      FROM information_schema.columns
      WHERE table_schema = 'public'
        AND table_name IN ('library_albums', 'library_artists')
        AND column_name = 'unreconciled_reason'
      ORDER BY table_name
    `)

    expect(res.rows).toEqual([
      {
        table_name: 'library_albums',
        column_name: 'unreconciled_reason',
        data_type: 'text',
        is_nullable: 'YES',
      },
      {
        table_name: 'library_artists',
        column_name: 'unreconciled_reason',
        data_type: 'text',
        is_nullable: 'YES',
      },
    ])
  })

  it('db.execute returns the {rows} shape upgrade.ts/health depend on', async () => {
    const res = await db.execute(sql`SELECT 1 AS x`)
    expect(Array.isArray(res.rows)).toBe(true)
    expect((res.rows[0] as { x: number }).x).toBe(1)
  })

  it('getPendingMigrations works against pglite introspection', async () => {
    const status = await getPendingMigrations(db as never)
    expect(status.pendingCount).toBe(0)
    expect(status.targetVersion).not.toBeNull()
  })

  it('caps queries with a 30s statement_timeout, matching the Postgres path', async () => {
    const client = new PGlite() // in-memory
    await applyPgliteStatementTimeout(client)
    const res = await client.query<{ statement_timeout: string }>('SHOW statement_timeout')
    expect(res.rows[0]?.statement_timeout).toBe('30s')
  }, 20_000)

  it('round-trips a backup on pglite', async () => {
    await db.execute(sql`INSERT INTO settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING`)
    const backup = await createBackup(db as never, { includeCaches: true })
    const result = await restoreBackup(db as never, backup, { force: true })
    expect(result.tablesRestored.settings).toBeGreaterThanOrEqual(1)
    expect(result.warnings).toEqual([])
  })

  // Migration 0046 converted every legacy `serial` primary key to
  // `GENERATED BY DEFAULT AS IDENTITY`. BY DEFAULT (not ALWAYS) is load-bearing:
  // backup restore inserts explicit ids, which ALWAYS would reject.
  it('exposes all id primary keys as BY DEFAULT identity columns', async () => {
    const res = await db.execute<{
      is_identity: string
      identity_generation: string | null
    }>(sql`
      SELECT is_identity, identity_generation
      FROM information_schema.columns
      WHERE table_schema = 'public' AND column_name = 'id'
    `)
    expect(res.rows.length).toBe(27)
    expect(res.rows.every((r) => r.is_identity === 'YES')).toBe(true)
    expect(res.rows.every((r) => r.identity_generation === 'BY DEFAULT')).toBe(true)
  })

  it('auto-assigns identity ids yet still accepts explicit ids (BY DEFAULT)', async () => {
    const [auto] = await db
      .insert(schema.users)
      .values({ username: 'identity-auto', passwordHash: 'x' })
      .returning()
    expect(typeof auto?.id).toBe('number')

    const [explicit] = await db
      .insert(schema.users)
      .values({ id: 987654, username: 'identity-explicit', passwordHash: 'x' })
      .returning()
    expect(explicit?.id).toBe(987654)
  })

  // Much app code calls .toISOString()/.getTime() on selected timestamp columns.
  // Confirm drizzle's timestamp({withTimezone}) maps to a JS Date under PGlite,
  // selected through the QUERY BUILDER (not raw execute), for a representative table.
  it('returns timestamptz columns as Date via the query builder', async () => {
    const [row] = await db
      .insert(schema.users)
      .values({ username: 'tz-probe', passwordHash: 'x' })
      .returning()
    expect(row).toBeDefined()
    expect(row?.createdAt).toBeInstanceOf(Date)
  })
})

it('persists waiting approval options and discovers them without a schema migration', async () => {
  const [artist] = await db
    .insert(schema.artists)
    .values({ mbid: '12345678-1234-1234-1234-123456789abc', name: 'Retry artist' })
    .returning()
  const [batch] = await db.insert(schema.recommendationBatches).values({}).returning()
  if (!artist || !batch) throw new Error('missing fixture')
  const [rec] = await db
    .insert(schema.recommendations)
    .values({ artistId: artist.id, batchId: batch.id, score: 0.9 })
    .returning()
  if (!rec) throw new Error('missing recommendation')
  const action = targetAction(
    { type: 'lidarr' },
    { success: false, targetType: 'lidarr', targetId: 1, error: 'HTTP 503' },
    { selectedAlbumIds: ['rg-1'], monitorOption: 'selected' },
  )
  await updateRecommendationStatus(db as never, rec.id, 'waiting', {
    targetActions: { 'lidarr-1': action },
  })
  expect((await getRecommendation(db as never, rec.id))?.targetActions).toEqual({
    'lidarr-1': action,
  })
  expect((await listWaitingApprovals(db as never)).map((r) => r.id)).toContain(rec.id)
  await updateRecommendationStatus(db as never, rec.id, 'added_to_lidarr', {
    targetActions: { 'lidarr-1': { status: 'added', externalId: 42 } },
  })
  expect((await listWaitingApprovals(db as never)).map((r) => r.id)).not.toContain(rec.id)
  await db.delete(schema.recommendations).where(eq(schema.recommendations.id, rec.id))
  await db.delete(schema.recommendationBatches).where(eq(schema.recommendationBatches.id, batch.id))
  await db.delete(schema.artists).where(eq(schema.artists.id, artist.id))
})

it("lists only the user's pending album recommendations and guards the unaddable update", async () => {
  const [user] = await db
    .insert(schema.users)
    .values({ username: 'sweep-user', passwordHash: 'x' })
    .returning()
  const [artist] = await db
    .insert(schema.artists)
    .values({ mbid: '22345678-1234-1234-1234-123456789abc', name: 'Sweep artist' })
    .returning()
  const [batch] = await db.insert(schema.recommendationBatches).values({}).returning()
  if (!user || !artist || !batch) throw new Error('missing fixture')
  const base = { artistId: artist.id, batchId: batch.id, score: 0.9, userId: user.id }
  const rows = await db
    .insert(schema.recommendations)
    .values([
      { ...base, kind: 'album', recommendedReleaseGroupId: 'rg-pending' },
      { ...base, kind: 'album', recommendedReleaseGroupId: 'rg-acted', status: 'approved' },
      { ...base, kind: 'artist' },
      { ...base, kind: 'album' },
    ])
    .returning()
  const [target] = rows
  if (!target) throw new Error('missing recommendation')

  const listed = await listPendingAlbumRecommendations(db as never, user.id, 200)
  expect(listed).toEqual([
    { id: target.id, artistMbid: artist.mbid, releaseGroupMbid: 'rg-pending' },
  ])

  expect(await markRecommendationUnaddable(db as never, target.id, 'blocked')).toBe(true)
  expect(await markRecommendationUnaddable(db as never, target.id, 'again')).toBe(false)
  const updated = await getRecommendation(db as never, target.id)
  expect(updated).toMatchObject({ status: 'unaddable', lidarrError: 'blocked' })
  expect(updated?.actedOnAt).toBeInstanceOf(Date)
})
